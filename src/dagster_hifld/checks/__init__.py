"""Manifest-backed catalog checks for publish partitions."""

from dagster import AssetCheckResult, AssetCheckSeverity, asset_check

from dagster_hifld.checks.common import (
    read_baseline_comparison_result,
    read_quality_check_result,
)
from dagster_hifld.partitions import parse_publish_partition_key
from dagster_hifld.resources import StagingStorageResource

_CHECK_DESC = "Read quality manifest generated by the catalog asset."
_BASELINE_CHECK_DESC = "Compare version against v20260214 baseline (columns + row count)."


@asset_check(
    asset=["publish", "catalog"],
    name="quality_manifest",
    description=_CHECK_DESC,
)
def publish_catalog_quality_manifest(
    context,
    staging_storage: StagingStorageResource,
) -> AssetCheckResult:
    if not context.has_partition_key:
        return AssetCheckResult(
            passed=False,
            metadata={"reason": "no_partition_selected"},
            severity=AssetCheckSeverity.WARN,
        )
    dataset_slug, file_slug, version = parse_publish_partition_key(context.partition_key)
    result = read_quality_check_result(
        staging_storage=staging_storage,
        dataset_slug=dataset_slug,
        file_slug=file_slug,
        version=version,
    )
    return AssetCheckResult(
        passed=result.passed,
        metadata=result.metadata,
        severity=AssetCheckSeverity.WARN,
    )


@asset_check(
    asset=["publish", "catalog"],
    name="baseline_comparison",
    description=_BASELINE_CHECK_DESC,
)
def publish_catalog_baseline_comparison(
    context,
    staging_storage: StagingStorageResource,
) -> AssetCheckResult:
    if not context.has_partition_key:
        return AssetCheckResult(
            passed=False,
            metadata={"reason": "no_partition_selected"},
        )
    dataset_slug, file_slug, version = parse_publish_partition_key(context.partition_key)
    return read_baseline_comparison_result(
        staging_storage=staging_storage,
        dataset_slug=dataset_slug,
        file_slug=file_slug,
        version=version,
    )


hifld_asset_checks = [
    publish_catalog_quality_manifest,
    publish_catalog_baseline_comparison,
]
