"""Manifest-backed catalog checks derived from supported dataset/file pairs."""

from dagster import AssetCheckResult, asset_check

from dagster_hifld.assets.supported_assets import SUPPORTED_DATASET_FILES
from dagster_hifld.checks.common import (
    read_baseline_comparison_result,
    read_quality_check_result,
)
from dagster_hifld.resources import StagingStorageResource

_CHECK_DESC = "Read quality manifest generated by the catalog asset."
_BASELINE_CHECK_DESC = "Compare version against v20260214 baseline (columns + row count)."


def _make_manifest_check(dataset_slug: str, file_slug: str):
    check_name = f"check_{dataset_slug}_{file_slug}".replace("-", "_")

    @asset_check(
        asset=["catalog", dataset_slug, file_slug],
        name=check_name,
        description=_CHECK_DESC,
    )
    def _manifest_check(
        context,
        staging_storage: StagingStorageResource,
    ) -> AssetCheckResult:
        if not context.has_partition_key:
            return AssetCheckResult(
                passed=False,
                metadata={"reason": "no_partition_selected"},
            )
        return read_quality_check_result(
            staging_storage=staging_storage,
            dataset_slug=dataset_slug,
            file_slug=file_slug,
            version=context.partition_key,
        )

    return _manifest_check


def _make_baseline_check(dataset_slug: str, file_slug: str):
    check_name = f"baseline_{dataset_slug}_{file_slug}".replace("-", "_")

    @asset_check(
        asset=["catalog", dataset_slug, file_slug],
        name=check_name,
        description=_BASELINE_CHECK_DESC,
    )
    def _baseline_check(
        context,
        staging_storage: StagingStorageResource,
    ) -> AssetCheckResult:
        if not context.has_partition_key:
            return AssetCheckResult(
                passed=False,
                metadata={"reason": "no_partition_selected"},
            )
        return read_baseline_comparison_result(
            staging_storage=staging_storage,
            dataset_slug=dataset_slug,
            file_slug=file_slug,
            version=context.partition_key,
        )

    return _baseline_check


hifld_asset_checks = [
    _make_manifest_check(spec.dataset_slug, spec.file_slug)
    for spec in SUPPORTED_DATASET_FILES
] + [
    _make_baseline_check(spec.dataset_slug, spec.file_slug)
    for spec in SUPPORTED_DATASET_FILES
]
