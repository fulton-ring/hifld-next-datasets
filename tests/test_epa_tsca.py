from urllib.parse import parse_qs, urlsplit
import unittest
import hashlib
import tempfile
from pathlib import Path
from unittest.mock import patch

import pyarrow as pa

from dagster_hifld.assets.epa_tsca import (
    epa_frs_toxic_substances_control_act_tsca,
    epa_tsca_draft_schedule,
)
from dagster_hifld.definitions import defs
from dagster_hifld.sources.epa_tsca import (
    DATASET_SLUG,
    EXPECTED_COUNT,
    ITEM_ID,
    LAYER_ID,
    LAYER_URL,
    LICENSE_URL,
    PROPOSED_PHYSICAL_TYPE_MAPPING,
    PAGE_SIZE,
    _item_provenance,
    _arrow_type,
    _feature_urls,
    _finalize_epa_tsca,
)
from dagster_hifld.resources import StagingStorageResource


class EpaTscaDraftTests(unittest.TestCase):
    def test_source_is_explicit_and_draft_only(self):
        self.assertEqual(DATASET_SLUG, "epa-frs-toxic-substances-control-act-tsca")
        self.assertEqual(ITEM_ID, "3c8a335f4b5243a188fd75472459e567")
        self.assertEqual(LAYER_ID, 0)
        self.assertEqual(epa_tsca_draft_schedule.default_status.value, "STOPPED")
        keys = defs.resolve_asset_graph().get_all_asset_keys()
        self.assertTrue(any(key.path == ["ingest", DATASET_SLUG, DATASET_SLUG] for key in keys))
        self.assertTrue(epa_frs_toxic_substances_control_act_tsca.keys)

    def test_paging_covers_population_without_skipping_ids(self):
        ids = list(range(1, EXPECTED_COUNT + 1))
        urls = _feature_urls(ids)
        pages = [(name, url) for name, url in urls if name.startswith("page_")]
        self.assertEqual(len(pages), (EXPECTED_COUNT + PAGE_SIZE - 1) // PAGE_SIZE)
        offsets = []
        for _, url in pages:
            query = parse_qs(urlsplit(url).query)
            offsets.append(int(query["resultOffset"][0]))
            self.assertEqual(query["where"], ["1=1"])
            self.assertEqual(query["resultRecordCount"], [str(PAGE_SIZE)])
            self.assertEqual(query["orderByFields"], ["OBJECTID ASC"])
            self.assertEqual(query["outFields"], ["*"])
            self.assertEqual(query["returnGeometry"], ["true"])
            self.assertEqual(query["outSR"], ["4269"])
            self.assertLess(len(url), 1800)
        self.assertEqual(offsets, list(range(0, EXPECTED_COUNT, PAGE_SIZE)))
        self.assertEqual(pages[-1][0], "page_026")
        self.assertIn(LAYER_URL, pages[0][1])

    def test_source_date_fields_keep_millisecond_timestamp_type(self):
        field = {"name": "CREATE_DATE", "type": "esriFieldTypeDate", "length": 8}
        self.assertEqual(_arrow_type(field), pa.timestamp("ms", tz="UTC"))

    def test_item_provenance_is_source_backed_and_type_maps_stay_proposed(self):
        portal_metadata = {
            "licenseInfo": ("Unless otherwise specified, EPA data are in the public domain under "
                             "17 U.S.C. § 105. See <a href=\"" + LICENSE_URL + "\">license</a>."),
            "accessInformation": "This EPA Geospatial dataset is generated by the EPA FRS Support team for TSCA.",
        }
        claims = _item_provenance(portal_metadata)
        self.assertEqual(claims["license"], LICENSE_URL)
        self.assertIn("EPA FRS Support team", claims["attribution"])
        self.assertEqual(PROPOSED_PHYSICAL_TYPE_MAPPING["esriFieldTypeOID"],
                         {"arrow": "int64", "status": "proposed_unapproved"})
        self.assertEqual(PROPOSED_PHYSICAL_TYPE_MAPPING["esriFieldTypeDate"],
                         {"arrow": "timestamp(ms, UTC)", "status": "proposed_unapproved"})
        with self.assertRaisesRegex(ValueError, "item_license_declaration_missing_or_changed"):
            _item_provenance({**portal_metadata, "licenseInfo": "No license text"})

    def test_synthetic_capture_finalizes_and_reuses_sealed_candidate(self):
        raw, wire = b'{"synthetic":true}', b'{"synthetic":true}'
        receipt = {
            "method": "GET", "url": "https://example.invalid/synthetic",
            "final_url": "https://example.invalid/synthetic", "observed_at": "2026-10-19T00:00:00+00:00",
            "status": 200, "complete_body": True, "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest(),
            "wire_bytes": len(wire), "wire_sha256": hashlib.sha256(wire).hexdigest(),
        }
        fields = [{"name":"OBJECTID", "type":"esriFieldTypeOID", "nullable":False}]
        extracted = {"features":[{"attributes":{"OBJECTID":7}, "geometry":{"x":-77.0,"y":38.0}}],
                     "audit":{"source_record_sha256":"a"*64, "source_geometry_sha256":"b"*64,
                              "source_schema_sha256":"c"*64, "source_feature_count":1,
                              "source_id_sha256":"d"*64, "source_crs_epsg":4269,
                              "geometry_type":"Point", "null_geometry_count":0,
                              "unique_source_id_count":1, "portal_item_id":ITEM_ID,
                              "portal_owner":"EPA_GEO", "portal_modified_epoch_ms":None,
                              "portal_modified_is_source_release_date":False}}
        provenance = {"license":LICENSE_URL, "attribution":"EPA FRS Support team TSCA"}
        with tempfile.TemporaryDirectory() as tmp:
            storage = StagingStorageResource(local_dir=tmp, use_local=True, backend="local")
            capture_root = Path(tmp) / "capture"
            capture_root.mkdir()
            (capture_root / "portal_item.wire").write_bytes(wire)
            with patch("dagster_hifld.sources.epa_tsca._code_identity", return_value={"code_commit":"synthetic","files":[]}), \
                 patch("dagster_hifld.sources.epa_tsca.validate_construction_code_identity"), \
                 patch("dagster_hifld.sources.epa_frs_common.validate_construction_code_identity"):
                first = _finalize_epa_tsca(storage, "synthetic-run", capture_root,
                    {"portal_item":(raw, receipt)}, fields, extracted, provenance)
                self.assertFalse(first["release_accepted"])
                second = _finalize_epa_tsca(storage, "synthetic-run-2", capture_root,
                    {"portal_item":(raw, receipt)}, fields, extracted, provenance)
            self.assertEqual(first["version"], second["version"])
            self.assertTrue(second.get("reused"))


if __name__ == "__main__":
    unittest.main()
