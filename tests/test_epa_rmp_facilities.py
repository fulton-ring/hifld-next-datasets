def _capture_fixture(*, num_views=(10, 11), data_edit=(1000, 1000), transfer=False,
                    expected_count=2, page_size=1000, final_transfer=False):
    fields = [
        {"name": "OBJECTID", "type": "esriFieldTypeOID", "alias": "Object ID", "nullable": False},
        {"name": "REGISTRY_ID", "type": "esriFieldTypeString", "alias": "Registry ID", "length": 12, "nullable": False},
        {"name": "CREATE_DATE", "type": "esriFieldTypeDate", "alias": "Created", "nullable": True},
    ]
    item = {"id": "370365ee65ef46bc8f1b010aad931294", "owner": "EPA_GEO", "access": "public",
            "url": "https://services.arcgis.com/cJ9YHowT8TU7DUyn/arcgis/rest/services/FRS_INTERESTS_RMP/FeatureServer",
            "type": "Feature Service", "modified": 900, "lastViewed": 800, "numViews": num_views[0],
            "description": "Facilities linked to the Risk Management Plan (RMP) System.",
            "accessInformation": "Generated by EPA FRS Support.",
            "licenseInfo": "Public domain under 17 U.S.C. § 105."}
    item_after = {**item, "numViews": num_views[1]}
    service = {"serviceItemId": item["id"], "layers": [{"id": 0, "name": "RMP"}]}
    layer = {"name": "RMP", "geometryType": "esriGeometryPoint", "objectIdField": "OBJECTID",
             "maxRecordCount": 2000, "spatialReference": {"latestWkid": 4269},
             "advancedQueryCapabilities": {"supportsPagination": True},
             "extent": {"xmin": -77.1, "ymin": 39.4, "xmax": -76.9, "ymax": 39.6},
             "editingInfo": {"dataLastEditDate": data_edit[0], "schemaLastEditDate": 700}, "fields": fields}
    layer_after = json.loads(json.dumps(layer)); layer_after["editingInfo"]["dataLastEditDate"] = data_edit[1]
    features = [{"attributes": {"OBJECTID": oid, "REGISTRY_ID": f"{oid:012d}",
                                 "CREATE_DATE": 1756252800000 if oid % 2 else None},
                 "geometry": {"x": -77.0, "y": 39.5} if oid % 2 else None}
                for oid in range(1, expected_count + 1)]
    pages = {f"features_{i:03d}": {"features": features[i * page_size:(i + 1) * page_size],
                                    "spatialReference": {"latestWkid": 4269},
                                    "exceededTransferLimit": transfer if i < (expected_count + page_size - 1) // page_size - 1 else final_transfer}
             for i in range((expected_count + page_size - 1) // page_size)}
    docs = {
        "portal_item_before": item, "portal_item_after": item_after,
        "service_before": service, "service_after": service,
        "layer_before": layer, "layer_after": layer_after,
        "count_before": {"count": expected_count}, "count_after": {"count": expected_count},
        "ids_before": {"objectIds": list(range(expected_count, 0, -1))},
        "ids_after": {"objectIds": list(range(expected_count, 0, -1))},
        "ids_seed": {"objectIds": list(range(1, expected_count + 1))}, **pages,
    }
    captures = {"epa_frs_sources_page": (b"Risk Management Plan (RMP); section 112(r)", {})}
    captures.update({name: (json.dumps(value, separators=(",", ":")).encode(), {})
                     if name.startswith("features_") else (_canonical(value), {})
                     for name, value in docs.items()})
    return captures, fields, features


class EpaRmpSourceTests(unittest.TestCase):
    def test_full_page_snapshot_and_null_geometry_are_retained_for_quality_gate(self):
        captures, fields, features = _capture_fixture()
        result = validate_source_captures(captures, expected_count=2, expected_field_count=3,
                                          expected_schema_sha256=None)
        self.assertEqual([row["attributes"]["OBJECTID"] for row in result["features"]], [1, 2])
        self.assertEqual(result["audit"]["null_geometry_count"], 1)
        self.assertEqual(result["audit"]["invalid_geometry_count"], 0)
        self.assertEqual(result["audit"]["source_crs_epsg"], 4269)
        parquet = _parquet_bytes(fields, features)
        table = pq.read_table(pa.BufferReader(parquet))
        self.assertEqual(table.schema.field("CREATE_DATE").type, pa.int64())
        self.assertEqual(table.column("CREATE_DATE").to_pylist(), [1756252800000, None])
        self.assertEqual(table.column("geometry").to_pylist()[1], None)
        self.assertTrue(table.schema.metadata[b"geo"].startswith(b'{"columns":{"geometry'))

    def test_duplicate_registry_and_extent_disagreement_are_diagnostics(self):
        captures, _, features = _capture_fixture(expected_count=3)
        features[1]["attributes"]["REGISTRY_ID"] = features[0]["attributes"]["REGISTRY_ID"]
        features[2]["geometry"] = {"x": 145.7412350699426, "y": 15.228676262399688}
        captures["features_000"] = (json.dumps({"features": features, "spatialReference": {"latestWkid": 4269},
                                                 "exceededTransferLimit": False}, separators=(",", ":")).encode(), {})
        result = validate_source_captures(captures, expected_count=3, expected_field_count=3,
                                          expected_schema_sha256=None)
        audit = result["audit"]
        self.assertEqual(audit["unique_object_id_count"], 3)
        self.assertEqual(audit["duplicate_registry_id_rows"], 1)
        self.assertEqual(audit["duplicate_registry_ids"][0]["object_ids"], [1, 2])
        self.assertEqual(audit["invalid_geometry_count"], 0)
        self.assertEqual(audit["extent_disagreement_count"], 1)
        self.assertEqual(audit["extent_disagreement_features"][0]["OBJECTID"], 3)
        self.assertEqual(audit["observed_geometry_bbox"][2], 145.7412350699426)

    def test_full_intermediate_transfer_limit_page_requires_exact_union(self):
        captures, _, _ = _capture_fixture(expected_count=3, page_size=2, transfer=True)
        result = validate_source_captures(captures, expected_count=3, expected_field_count=3,
                                          expected_schema_sha256=None, page_size=2)
        self.assertEqual(result["audit"]["source_feature_count"], 3)

        captures, _, _ = _capture_fixture(expected_count=3, page_size=2, transfer=True, final_transfer=True)
        with self.assertRaisesRegex(ValueError, "source_page_error_or_truncation"):
            validate_source_captures(captures, expected_count=3, expected_field_count=3,
                                     expected_schema_sha256=None, page_size=2)

    def test_only_numviews_is_ignored_across_arcgis_portal_snapshots(self):
        captures, _, _ = _capture_fixture()
        captures["portal_item_after"] = (_canonical({**json.loads(captures["portal_item_after"][0]), "title": "changed"}), {})
        with self.assertRaisesRegex(ValueError, "official_item_metadata_changed"):
            validate_source_captures(captures, expected_count=2, expected_field_count=3, expected_schema_sha256=None)

    def test_source_edit_and_final_transfer_limit_are_hard_failures(self):
        captures, _, _ = _capture_fixture(data_edit=(1000, 1001))
        with self.assertRaisesRegex(ValueError, "official_source_metadata_changed"):
            validate_source_captures(captures, expected_count=2, expected_field_count=3, expected_schema_sha256=None)
        captures, _, _ = _capture_fixture(final_transfer=True)
        with self.assertRaisesRegex(ValueError, "source_page_error_or_truncation"):
            validate_source_captures(captures, expected_count=2, expected_field_count=3, expected_schema_sha256=None)

    def test_field_roster_and_before_after_ids_are_pinned(self):
        captures, _, _ = _capture_fixture()
        layer = json.loads(captures["layer_after"][0]); layer["fields"].append(
            {"name": "unexpected", "type": "esriFieldTypeString", "nullable": True})
        captures["layer_after"] = (_canonical(layer), {})
        with self.assertRaisesRegex(ValueError, "official_source_metadata_changed"):
            validate_source_captures(captures, expected_count=2, expected_field_count=3, expected_schema_sha256=None)

        captures, _, _ = _capture_fixture()
        ids = json.loads(captures["ids_after"][0]); ids["objectIds"].append(3)
        captures["ids_after"] = (_canonical(ids), {})
        with self.assertRaisesRegex(ValueError, "source_id_population_drift"):
            validate_source_captures(captures, expected_count=2, expected_field_count=3, expected_schema_sha256=None)

    def test_complete_synthetic_capture_manifest_candidate_and_cache_reuse(self):
        captures, fields, _ = _capture_fixture()
        captures["ids_seed"] = (_canonical({"objectIds": [2, 1]}), {})
        schema_sha = hashlib.sha256(_canonical(fields)).hexdigest()
        urls = [(name, f"https://{'www.epa.gov' if name.startswith('epa_frs') else 'www.arcgis.com' if name.startswith('portal') else 'services.arcgis.com'}/{name}") for name in captures
                if name not in {"ids_seed"}]
        urls.insert(0, ("ids_seed", "https://services.arcgis.com/ids_seed"))

        observation_time = ["2026-10-19T00:00:00Z"]
        def fake_get(_client, url, capture_root, name, *, max_bytes):
            body = captures[name][0]
            wire = body
            (capture_root / f"{name}.body").write_bytes(body)
            (capture_root / f"{name}.wire").write_bytes(wire)
            receipt = {"method": "GET", "url": url, "final_url": url, "observed_at": observation_time[0],
                       "status": 200, "complete_body": True, "bytes": len(body), "sha256": hashlib.sha256(body).hexdigest(),
                       "wire_bytes": len(wire), "wire_sha256": hashlib.sha256(wire).hexdigest(),
                       "content_encoding": "identity", "content_length": len(body), "error_code": None}
            (capture_root / f"{name}.receipt.json").write_bytes(_canonical(receipt) + b"\n")
            return body, receipt

        with tempfile.TemporaryDirectory() as tmp:
            storage = StagingStorageResource(local_dir=str(Path(tmp) / "stage"), use_local=True, backend="local")
            replay_root = Path(tmp) / "reference-documentation"
            replay_root.mkdir()
            source_page = captures["epa_frs_sources_page"][0]
            (replay_root / "epa_frs_sources_page.body").write_bytes(source_page)
            (replay_root / "epa_frs_sources_page.wire").write_bytes(source_page)
            replay_receipt = {"method": "GET", "url": EPA_FRS_DATA_SOURCES_URL,
                              "final_url": EPA_FRS_DATA_SOURCES_URL,
                              "observed_at": "2026-10-19T19:55:32.426036+00:00",
                              "status": 200, "complete_body": True,
                              "content_encoding": "identity",
                              "bytes": len(source_page), "sha256": hashlib.sha256(source_page).hexdigest(),
                              "wire_bytes": len(source_page), "wire_sha256": hashlib.sha256(source_page).hexdigest()}
            (replay_root / "epa_frs_sources_page.receipt.json").write_bytes(_canonical(replay_receipt) + b"\n")
            args = {"version": "synthetic-fixture", "capture_directory": str(Path(tmp) / "captures"),
                    "supporting_document_replay_directory": str(replay_root)}
            with (patch("dagster_hifld.sources.epa_rmp_facilities.SOURCE_COUNT", 2),
                  patch("dagster_hifld.sources.epa_rmp_facilities.SOURCE_FIELD_COUNT", 3),
                  patch("dagster_hifld.sources.epa_rmp_facilities.SOURCE_SCHEMA_SHA256", schema_sha),
                  patch("dagster_hifld.sources.epa_rmp_facilities._source_urls", return_value=urls),
                  patch("dagster_hifld.sources.epa_rmp_facilities.validate_construction_code_identity"),
                  patch("dagster_hifld.sources.epa_frs_common.validate_construction_code_identity"),
                  patch("dagster_hifld.sources.epa_rmp_facilities.capture_get", side_effect=fake_get)):
                first = capture_epa_rmp_facilities(storage, **args)
                self.assertFalse(first["release_accepted"])
                self.assertEqual(first["feature_count"], 2)
                self.assertFalse(epa_emergency_response_rmp_facilities_complete(first).passed)
                prefix = f"{first['dataset_slug']}/{first['file_slug']}/{first['version']}"
                manifest = json.loads(storage.read_key(prefix + "/metadata/source_manifest.json"))
                candidate = json.loads(storage.read_key(prefix + "/metadata/candidate_ready.json"))
                self.assertFalse(manifest["approved"])
                self.assertIsNone(manifest["date_issued"])
                self.assertIn("release_date_unknown_reason", manifest["inputs"][0])
                doc_input = next(row for row in manifest["inputs"] if row["input_id"] == "epa_frs_sources_page")
                self.assertEqual(doc_input["capture_mode"], "documentation_replay")
                self.assertEqual(doc_input["role"], "producer_publication")
                self.assertIn("program relationship only", doc_input["evidence_scope"])
                self.assertIn("Unknown for the EPA FRS data-sources reference page", doc_input["license"])
                self.assertEqual(doc_input["retrieved_at"], replay_receipt["observed_at"])
                stored_replay = json.loads(storage.read_key(prefix + "/raw/epa_frs_sources_page.receipt.json"))
                self.assertTrue(stored_replay["documentation_replay"])
                self.assertFalse(stored_replay["captured_for_dataset_refresh"])
                self.assertFalse(candidate["release_accepted"])
                self.assertIn(prefix + "/raw/features_000.body", storage.list_prefix(prefix))
                # Catalog-derived documents are permitted by the shared
                # cache policy and must not alter the sealed source roster.
                quality = {"schema_version": 1, "source": "fixture", "passed": False,
                           "blocking": ["synthetic_baseline_pending"]}
                write_immutable(storage, prefix + "/metadata/quality_manifest.json",
                                _canonical(quality) + b"\n")
                observation_time[0] = "2026-10-20T00:00:00Z"
                second = capture_epa_rmp_facilities(storage, **args)
                self.assertTrue(second["reused"])
                self.assertEqual(first["version"], second["version"])
                self.assertEqual(second["duplicate_registry_id_rows"], 0)
                self.assertEqual(second["extent_disagreement_count"], 0)


