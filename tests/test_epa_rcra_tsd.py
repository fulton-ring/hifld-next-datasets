class EpaRcraTsdTests(unittest.TestCase):
    def test_pagination_uses_short_offset_requests_and_exact_batches(self):
        pages = [(name, url) for name, url in _urls(list(range(1, 1966))) if name.startswith("page_")]
        self.assertEqual([name for name, _ in pages], ["page_000", "page_001"])
        self.assertTrue(all(len(url) < 1800 for _, url in pages))
        first = parse_qs(urlsplit(pages[0][1]).query)
        self.assertNotIn("objectIds", first)
        self.assertEqual(first["resultOffset"], ["0"])
        self.assertEqual(first["resultRecordCount"], ["1000"])

    def test_asset_check_and_refresh_schedule_are_registered_and_stopped(self):
        asset_key = AssetKey(["ingest", "epa-rcra-treatment-storage-and-disposal-facilities",
                              "epa-rcra-treatment-storage-and-disposal-facilities"])
        self.assertIn(asset_key, defs.resolve_asset_graph().get_all_asset_keys())
        self.assertTrue(any(key.asset_key == asset_key and key.name == "epa_rcra_tsd_complete"
                            for definition in defs.asset_checks for key in definition.check_keys))
        schedule = next(item for item in defs.schedules if item.name == "epa_rcra_tsd_draft_refresh_schedule")
        self.assertEqual(schedule.default_status.name, "STOPPED")

    def test_exact_item_snapshot_and_complete_page_with_volatile_view_count(self):
        _, _, docs = _fixture()
        layer, fields, extracted = validate_capture_documents(
            {k:json.dumps(v).encode() for k,v in docs.items()}, expected_schema_sha256=None)
        self.assertEqual(layer["name"], LAYER_NAME)
        self.assertEqual(fields[1]["name"], "REGISTRY_ID")
        self.assertEqual(extracted["audit"]["source_feature_count"], 2)
        self.assertEqual(extracted["audit"]["source_crs_epsg"], 4269)

    def test_native_arrow_keeps_dates_as_epoch_milliseconds_and_oids_as_int64(self):
        fields, rows, _ = _fixture()
        self.assertEqual(_arrow_type(fields[0]), pa.int64())
        self.assertEqual(_arrow_type(fields[2]), pa.int64())
        table = pq.read_table(pa.BufferReader(native_geoparquet(fields, rows)))
        self.assertEqual(table.column("CREATE_DATE").to_pylist(), [1771391229000, None])
        self.assertEqual(table.column("OBJECTID").to_pylist(), [1, 2])
        self.assertEqual(table.num_rows, 2)

    def test_page_and_source_roster_drift_fail_closed(self):
        _, _, docs = _fixture()
        docs["page_000"]["features"] = docs["page_000"]["features"][:1]
        with self.assertRaisesRegex(ValueError, "source_page_incomplete_or_unordered"):
            validate_capture_documents({k:json.dumps(v).encode() for k,v in docs.items()}, expected_schema_sha256=None)

    def test_unapproved_field_roster_change_is_quarantinable_drift(self):
        _, _, docs = _fixture()
        with self.assertRaisesRegex(ValueError, "source_schema_drift"):
            validate_capture_documents({k:json.dumps(v).encode() for k,v in docs.items()})

    def test_tiny_fixture_capture_finalizes_candidate_then_verifies_cache_reuse(self):
        fields, rows, docs = _fixture()
        payloads = {name:json.dumps(value,separators=(",", ":")).encode() for name,value in docs.items()
                    if name not in {"epa_item_after", "page_000"}}
        payloads["ids_seed"] = json.dumps({"objectIds":[1,2]}).encode()
        payloads["page_000"] = json.dumps({"features":rows,"exceededTransferLimit":False,"spatialReference":{"wkid":4269}}).encode()
        payloads["epa_item"] = json.dumps(docs["epa_item"]).encode()
        payloads["epa_item_after"] = json.dumps(docs["epa_item_after"]).encode()
        payloads["layer_before"] = json.dumps(docs["layer_before"]).encode()
        payloads["layer_after"] = json.dumps(docs["layer_after"]).encode()
        payloads["service_before"] = json.dumps(docs["service_before"]).encode()
        payloads["service_after"] = json.dumps(docs["service_after"]).encode()
        payloads["ids_before"] = json.dumps(docs["ids_before"]).encode()
        payloads["ids_after"] = json.dumps(docs["ids_after"]).encode()
        payloads["count_before"] = json.dumps(docs["count_before"]).encode()
        payloads["count_after"] = json.dumps(docs["count_after"]).encode()
        tick = {"value":0}

        def fake_capture(_client, url, capture_root, name, *, max_bytes):
            tick["value"] += 1
            body = payloads[name]
            capture_root.mkdir(parents=True, exist_ok=True)
            (capture_root / f"{name}.wire").write_bytes(body)
            receipt = {"method":"GET","url":url,"final_url":url,"observed_at":datetime.now(timezone.utc).isoformat(),
                       "status":200,"complete_body":True,"wire_bytes":len(body),"wire_sha256":hashlib.sha256(body).hexdigest(),
                       "bytes":len(body),"sha256":hashlib.sha256(body).hexdigest()}
            return body, receipt

        repo = Path(__file__).resolve().parents[1]
        commit = subprocess.check_output(["git","rev-parse","HEAD"],cwd=repo,text=True).strip()
        identity = {"code_commit":commit,"files":{},"python":"fixture"}
        original_validator = rcra.validate_capture_documents
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            storage = StagingStorageResource(local_dir=str(root / "stage"), use_local=True, backend="local")
            (root / "stage").mkdir()
            with (patch.object(rcra, "capture_get", side_effect=fake_capture),
                  patch.object(rcra, "validate_capture_documents", side_effect=lambda captured: original_validator(captured, expected_schema_sha256=None)),
                  patch.object(rcra, "_identity", return_value=identity),
                  patch.object(rcra, "validate_construction_code_identity"),
                  patch.object(frs_common, "validate_construction_code_identity")):
                first = rcra.capture_epa_rcra_tsd(storage, version="fixture-run", capture_directory=str(root / "captures"))
                prefix = first["candidate_ready"].split("/metadata/", 1)[0]
                sealed_manifest = storage.read_key(prefix + "/metadata/source_manifest.json")
                manifest_sha = hashlib.sha256(sealed_manifest).hexdigest()
                derived = {
                    "metadata/quality_manifest.json": b'{"quality_check_passed":false}',
                    "metadata/data_dictionary.json": b'{"fixture":true}',
                    "metadata/resolved_provenance.json": b'{"fixture":true}',
                    "metadata/source/quality_manifest.json": b'{"fixture":true}',
                    "metadata/source/data_dictionary.json": b'{"fixture":true}',
                    "metadata/source/source_manifest.json": sealed_manifest,
                    f"metadata/source/version_{manifest_sha}_source_manifest.json": sealed_manifest,
                }
                for name, body in derived.items():
                    rcra.write_immutable(storage, prefix + "/" + name, body)
                second = rcra.capture_epa_rcra_tsd(storage, version="fixture-run-2", capture_directory=str(root / "captures"))
            self.assertEqual(first["version"], second["version"])
            self.assertFalse(first["release_accepted"])
            self.assertTrue(second["reused"])
            candidate = first["candidate_ready"]
            self.assertEqual(json.loads(storage.read_key(candidate))["approved"], False)
            self.assertIn(prefix + "/raw/epa_item.body", storage.list_prefix(prefix))


